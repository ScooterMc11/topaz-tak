/// "TAK6" as a big-endian u32; written little-endian to match the trainer's native-endian read.
const TAK_MAGIC: u32 = u32::from_be_bytes(*b"TAK6");
const CHUNK_HEADER_SIZE: usize = 8;
/// Flush a chunk once its body reaches roughly this size (closed only on entry boundaries).
const TARGET_CHUNK_BYTES: usize = 8 * 1024;
/// Eval scale shared with the trainer: `sigmoid(score / EVAL_SCALE) == win_prob`.
const EVAL_SCALE: f64 = 400.0;

#[derive(Clone, Debug)]
pub struct DataGen5Config {
    /// Total number of self-play games to generate.
    pub num_games: usize,
    /// Worker threads; each owns its own tiltak subprocess.
    pub threads: usize,
    /// tiltak search budget per move (`go nodes N`).
    pub max_nodes: u64,
    /// Random opening plies generated by Topaz before tiltak takes over (includes the forced ply-1
    /// `2xx` double placement). 6 = the user's "random 6-ply" opening.
    pub random_plies: usize,
    /// Hard cap on plies per game; reaching it scores the game a draw.
    pub max_plies: usize,
    /// Half-komi passed to tiltak (`setoption HalfKomi`); 0 for the black-stack variant.
    pub half_komi: u8,
    /// Path to the tiltak TEI binary (e.g. `../tiltak/target/release/tei.exe`).
    pub tiltak_path: String,
    /// Optional opening book (TPS per line, move_num>=2). If set, games start from book positions
    /// (standard play); if None, openings are generated internally (black-stack).
    pub book_path: Option<String>,
    /// Output `.bin` path.
    pub output: String,
}

impl Default for DataGen5Config {
    fn default() -> Self {
        Self {
            num_games: 1000,
            threads: 4,
            max_nodes: 10_000,
            random_plies: 6,
            max_plies: 120,
            half_komi: 0,
            tiltak_path: "../tiltak/target/release/tei.exe".to_string(),
            book_path: None,
            output: "data5.bin".to_string(),
        }
    }
}

// ---------------------------------------------------------------------------
// TAK6 serialization (mirrors crate::datagen, typed for the size-5 BoardData)
// ---------------------------------------------------------------------------

/// Append one position as a full-snapshot entry (`plys_len = 0`) to a chunk body buffer.
fn push_entry(body: &mut Vec<u8>, data: &BoardData5, score: i16, result: u8, half_komi: u8) {
    body.push(data.caps[0]);
    body.push(data.caps[1]);
    body.push(data.white_to_move as u8);
    body.push(0); // extra_score
    body.extend_from_slice(&score.to_le_bytes());
    body.push(result);
    body.push(half_komi);
    body.push(data.data_len);
    body.push(0); // plys_len
    for i in 0..data.data_len as usize {
        // The engine's PieceSquare byte is exactly the trainer's PSquare byte.
        body.push(data.data[i].0);
    }
}

/// Wrap an accumulated entry body in a `ChunkHeader`.
fn make_chunk(body: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(CHUNK_HEADER_SIZE + body.len());
    out.extend_from_slice(&TAK_MAGIC.to_le_bytes());
    out.extend_from_slice(&(body.len() as u32).to_le_bytes());
    out.extend_from_slice(body);
    out
}

/// Map a finished game's result to the side-to-move-relative label {0 = loss, 1 = draw, 2 = win}.
fn result_for(white_to_move: bool, outcome: GameResult) -> u8 {
    match outcome {
        GameResult::Draw => 1,
        GameResult::WhiteWin => {
            if white_to_move {
                2
            } else {
                0
            }
        }
        GameResult::BlackWin => {
            if white_to_move {
                0
            } else {
                2
            }
        }
    }
}

fn new_rng() -> Xoshiro256PlusPlus {
    let mut seed = [0u8; 32];
    getrandom::fill(&mut seed).expect("failed to seed rng");
    Xoshiro256PlusPlus::from_seed(seed)
}

/// Convert tiltak's STM win-probability into a side-to-move-relative score with
/// `sigmoid(score / EVAL_SCALE) == p`. Clamped to avoid infinities and stay within the trainer's
/// `|score| <= 9999` filter.
fn score_from_winprob(p: f64) -> i16 {
    let p = p.clamp(1e-3, 1.0 - 1e-3);
    let score = (EVAL_SCALE * (p / (1.0 - p)).ln()).round();
    score.clamp(-9000.0, 9000.0) as i16
}

/// Load an opening book: one TPS position per line (blank lines ignored).
fn load_book(path: &str) -> io::Result<Vec<String>> {
    let text = std::fs::read_to_string(path)?;
    let lines: Vec<String> = text
        .lines()
        .map(|l| l.trim().to_string())
        .filter(|l| !l.is_empty())
        .collect();
    if lines.is_empty() {
        return Err(io::Error::new(io::ErrorKind::InvalidData, format!("empty opening book: {path}")));
    }
    Ok(lines)
}

/// Build a game's starting board. With a book, start from a random book position (which must be at
/// `move_num >= 2` so the black-stack rule never fires — i.e. standard play). Without a book, start
/// from a fresh board and apply `random_plies` random flats (forced `2xx` at ply 1 -> black-stack).
fn start_board(book: &Option<Arc<Vec<String>>>, random_plies: usize, rng: &mut impl RngCore) -> Board5 {
    if let Some(book) = book {
        let line = &book[(rng.next_u32() as usize) % book.len()];
        Board5::try_from_tps(line).expect("book TPS should parse")
    } else {
        let mut board = Board5::new();
        for _ in 0..random_plies {
            if board.game_result().is_some() {
                break;
            }
            do_random_flat_move(&mut board, rng);
        }
        board
    }
}

/// Play one random flat placement (the forced `2xx` at ply 1 is itself a flat, so it is preserved).
/// Inlined here (rather than using `Board6::do_random_flat_move`) to keep this module size-isolated;
/// `pub(crate)` so `balance5` can reuse it.
pub(crate) fn do_random_flat_move(board: &mut Board5, rng: &mut impl RngCore) {
    let mut moves: Vec<GameMove> = Vec::new();
    generate_all_moves(board, &mut moves);
    let flats: Vec<GameMove> = moves
        .iter()
        .copied()
        .filter(|m| m.is_place_move() && matches!(m.place_piece(), Piece::WhiteFlat | Piece::BlackFlat))
        .collect();
    let pool = if flats.is_empty() { &moves } else { &flats };
    let idx = rng.next_u32() as usize % pool.len();
    board.do_move(pool[idx]);
}

