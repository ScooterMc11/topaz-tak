/// TEI subprocess client (also reused by `balance5` for tiltak-driven balance).
pub(crate) struct Tiltak {
    child: Child,
    stdin: BufWriter<ChildStdin>,
    stdout: BufReader<ChildStdout>,
    line: String,
}

impl Tiltak {
    pub(crate) fn spawn(path: &str, size: usize, half_komi: u8) -> io::Result<Self> {
        let mut child = Command::new(path)
            .stdin(Stdio::piped())
            .stdout(Stdio::piped())
            // tiltak logs "Failed to find move difference, creating new tree" to stderr on every
            // ply (we feed full TPS, not incremental moves), which floods at scale; discard it. A
            // real crash surfaces as EOF on stdout, which the self-play loop handles.
            .stderr(Stdio::null())
            .spawn()?;
        let stdin = BufWriter::new(child.stdin.take().unwrap());
        let stdout = BufReader::new(child.stdout.take().unwrap());
        let mut t = Self { child, stdin, stdout, line: String::new() };
        t.send("tei")?;
        t.wait_for("teiok")?;
        t.send(&format!("setoption name HalfKomi value {half_komi}"))?;
        t.send("isready")?;
        t.wait_for("readyok")?;
        Ok(t)
    }

    fn send(&mut self, cmd: &str) -> io::Result<()> {
        writeln!(self.stdin, "{cmd}")?;
        self.stdin.flush()
    }

    /// Read one line (trimmed), or `None` at EOF.
    fn read_line(&mut self) -> io::Result<Option<&str>> {
        self.line.clear();
        let n = self.stdout.read_line(&mut self.line)?;
        if n == 0 {
            Ok(None)
        } else {
            Ok(Some(self.line.trim_end()))
        }
    }

    fn wait_for(&mut self, token: &str) -> io::Result<()> {
        while let Some(line) = self.read_line()? {
            if line.starts_with(token) {
                return Ok(());
            }
        }
        Err(io::Error::new(io::ErrorKind::UnexpectedEof, format!("tiltak closed before '{token}'")))
    }

    pub(crate) fn new_game(&mut self, size: usize) -> io::Result<()> {
        self.send(&format!("teinewgame {size}"))
    }

    /// Ask tiltak for the best move + STM win-probability from a TPS position.
    pub(crate) fn bestmove(&mut self, tps: &str, nodes: u64) -> io::Result<Option<(String, f64)>> {
        self.send(&format!("position tps {tps}"))?;
        self.send(&format!("go nodes {nodes}"))?;
        let mut win_prob = 0.5;
        loop {
            let line = match self.read_line()? {
                Some(l) => l,
                None => return Ok(None), // engine died
            };
            if line.starts_with("info") {
                if let Some(p) = parse_info_winprob(line) {
                    win_prob = p;
                }
            } else if let Some(rest) = line.strip_prefix("bestmove ") {
                let mv = sanitize_move(rest.split_whitespace().next().unwrap_or(""));
                if mv.is_empty() {
                    return Ok(None);
                }
                return Ok(Some((mv, win_prob)));
            }
        }
    }
}

impl Drop for Tiltak {
    fn drop(&mut self) {
        let _ = self.send("quit");
        let _ = self.child.kill();
        let _ = self.child.wait();
    }
}

/// Parse the STM win-probability from a tiltak `info ... score cp <cp> ...` line.
/// tiltak emits `cp = (win_prob * 200 - 100)`, so `win_prob = (cp + 100) / 200`.
fn parse_info_winprob(line: &str) -> Option<f64> {
    let mut it = line.split_whitespace();
    while let Some(tok) = it.next() {
        if tok == "cp" {
            let cp: f64 = it.next()?.parse().ok()?;
            return Some(((cp + 100.0) / 200.0).clamp(0.0, 1.0));
        }
    }
    None
}

/// Strip PTN annotation suffixes (tak/road/quality marks) tiltak may append, e.g. `e3+*`.
fn sanitize_move(mv: &str) -> String {
    mv.trim_end_matches(['*', '!', '?', '\'']).to_string()
}

