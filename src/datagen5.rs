/// Play `num_games`, driving one tiltak subprocess; send finished chunks to the writer thread.
fn worker(
    num_games: usize,
    cfg: &DataGen5Config,
    book: Option<Arc<Vec<String>>>,
    tx: mpsc::Sender<Vec<u8>>,
    games_done: &AtomicU64,
    positions_done: &AtomicU64,
) -> io::Result<()> {
    let mut rng = new_rng();
    let mut tiltak = Tiltak::spawn(&cfg.tiltak_path, 5, cfg.half_komi)?;
    let mut body: Vec<u8> = Vec::with_capacity(TARGET_CHUNK_BYTES + 256);
    let mut positions: Vec<(BoardData5, i16)> = Vec::new();

    for _ in 0..num_games {
        positions.clear();
        tiltak.new_game(5)?;
        // Opening: a book position (standard, move_num>=2) or an internally generated black-stack one.
        let mut board = start_board(&book, cfg.random_plies, &mut rng);

        // tiltak plays out standard Tak from the opening TPS; record each position.
        let mut plies = 0;
        let mut hit_cap = false;
        while board.game_result().is_none() {
            if plies >= cfg.max_plies {
                hit_cap = true;
                break;
            }
            let tps = format!("{:?}", board);
            let (mv_str, p) = match tiltak.bestmove(&tps, cfg.max_nodes)? {
                Some(v) => v,
                None => break, // engine produced no move; abandon this game
            };
            let mv = match GameMove::try_from_ptn(&mv_str, &board) {
                Some(m) => m,
                None => {
                    eprintln!("datagen5: could not parse tiltak move '{mv_str}' at tps '{tps}'");
                    break;
                }
            };
            let data = build_nn_repr5(&board);
            positions.push((data, score_from_winprob(p)));
            board.do_move(mv);
            plies += 1;
        }

        // Backfill the result (draw if we hit the ply cap).
        let outcome = if hit_cap {
            GameResult::Draw
        } else {
            board.game_result().unwrap_or(GameResult::Draw)
        };
        for (data, score) in positions.iter() {
            let result = result_for(data.white_to_move, outcome);
            push_entry(&mut body, data, *score, result, cfg.half_komi);
        }
        positions_done.fetch_add(positions.len() as u64, Ordering::Relaxed);

        if body.len() >= TARGET_CHUNK_BYTES {
            if tx.send(make_chunk(&body)).is_err() {
                return Ok(());
            }
            body.clear();
        }

        let n = games_done.fetch_add(1, Ordering::Relaxed) + 1;
        if n % 100 == 0 {
            eprintln!("datagen5: {n} games, {} positions", positions_done.load(Ordering::Relaxed));
        }
    }

    if !body.is_empty() {
        let _ = tx.send(make_chunk(&body));
    }
    Ok(())
}

/// Generate a tiltak self-play dataset and write it to `cfg.output`.
pub fn run(cfg: DataGen5Config) -> io::Result<()> {
    assert!(cfg.threads >= 1, "need at least one thread");
    let start = Instant::now();
    println!(
        "datagen5: {} games, {} threads, tiltak {} nodes/move, {} random plies, komi {} -> {}",
        cfg.num_games, cfg.threads, cfg.max_nodes, cfg.random_plies, cfg.half_komi, cfg.output
    );
    println!("datagen5: tiltak binary = {}", cfg.tiltak_path);

    let book = match &cfg.book_path {
        Some(p) => {
            let b = Arc::new(load_book(p)?);
            println!("datagen5: opening book = {} ({} positions, standard play)", p, b.len());
            Some(b)
        }
        None => None,
    };

    let (tx, rx) = mpsc::channel::<Vec<u8>>();
    let out_path = cfg.output.clone();
    let writer = thread::spawn(move || -> io::Result<u64> {
        let mut file = BufWriter::new(File::create(&out_path)?);
        let mut bytes = 0u64;
        while let Ok(chunk) = rx.recv() {
            file.write_all(&chunk)?;
            bytes += chunk.len() as u64;
        }
        file.flush()?;
        Ok(bytes)
    });

    let games_done = Arc::new(AtomicU64::new(0));
    let positions_done = Arc::new(AtomicU64::new(0));

    let base = cfg.num_games / cfg.threads;
    let extra = cfg.num_games % cfg.threads;
    let mut handles = Vec::new();
    for t in 0..cfg.threads {
        let games = base + if t < extra { 1 } else { 0 };
        if games == 0 {
            continue;
        }
        let tx = tx.clone();
        let cfg = cfg.clone();
        let book = book.clone();
        let games_done = games_done.clone();
        let positions_done = positions_done.clone();
        handles.push(thread::spawn(move || {
            if let Err(e) = worker(games, &cfg, book, tx, &games_done, &positions_done) {
                eprintln!("datagen5: worker {t} failed: {e}");
            }
        }));
    }
    drop(tx);

    for h in handles {
        h.join().expect("worker thread panicked");
    }
    let bytes = writer.join().expect("writer thread panicked")?;

    let secs = start.elapsed().as_secs_f64();
    let positions = positions_done.load(Ordering::Relaxed);
    println!(
        "datagen5 done: {} games, {} positions, {:.1} MB in {:.1}s ({:.0} pos/s) -> {}",
        games_done.load(Ordering::Relaxed),
        positions,
        bytes as f64 / (1024.0 * 1024.0),
        secs,
        positions as f64 / secs.max(1e-9),
        cfg.output,
    );
    Ok(())
}

// ---------------------------------------------------------------------------
// Topaz self-play (NNUE5) datagen — for iterating past the tiltak label ceiling
// ---------------------------------------------------------------------------
//
// Once the engine's own net beats tiltak, tiltak's labels cap quality. This path self-plays with
// Topaz's NNUE5 search instead (AlphaZero-style: generate with the current best net, train the next
// one). It reuses this module's TAK6 writer / opening / threading. Topaz plays the black-stack rule
// natively (forced 2xx at move_num 1), so no TPS handoff is needed, and the recorded score is
// Topaz's own search eval — already on the trainer's `eval_scale=400` sigmoid scale, no conversion.

/// Hard depth cap; the node limit normally stops the search first.
const MAX_DEPTH: usize = 30;

#[derive(Clone, Debug)]
pub struct SelfPlay5Config {
    pub num_games: usize,
    pub threads: usize,
    /// Topaz search node cap per move.
    pub max_nodes: u64,
    pub random_plies: usize,
    pub max_plies: usize,
    /// Half-komi written to the TAK6 entries (0 for the black-stack variant).
    pub half_komi: u8,
    /// Optional opening book (TPS per line, move_num>=2). If set, games start from book positions
    /// (standard play); if None, openings are generated internally (black-stack).
    pub book_path: Option<String>,
    pub output: String,
    /// Transposition-table entries per worker thread.
    pub tt_size: usize,
}

impl Default for SelfPlay5Config {
    fn default() -> Self {
        Self {
            num_games: 1000,
            threads: 4,
            max_nodes: 5000,
            random_plies: 6,
            max_plies: 120,
            half_komi: 0,
            book_path: None,
            output: "data5_self.bin".to_string(),
            tt_size: 1 << 20,
        }
    }
}

/// Self-play `num_games` with Topaz NNUE5 search; send finished chunks to the writer thread.
fn worker_selfplay(
    num_games: usize,
    cfg: &SelfPlay5Config,
    book: Option<Arc<Vec<String>>>,
    tx: mpsc::Sender<Vec<u8>>,
    games_done: &AtomicU64,
    positions_done: &AtomicU64,
) {
    let mut rng = new_rng();
    let table = HashTable::new(cfg.tt_size);
    let mut body: Vec<u8> = Vec::with_capacity(TARGET_CHUNK_BYTES + 256);
    let mut positions: Vec<(BoardData5, i16)> = Vec::new();

    for _ in 0..num_games {
        table.clear();
        positions.clear();
        // Opening: a book position (standard, move_num>=2) or an internally generated black-stack one.
        let mut board = start_board(&book, cfg.random_plies, &mut rng);

        // Self-play to game end, recording each searched position + Topaz's eval.
        let mut plies = 0;
        let mut hit_cap = false;
        while board.game_result().is_none() {
            if plies >= cfg.max_plies {
                hit_cap = true;
                break;
            }
            let mut eval = NNUE5::default();
            let mut info = SearchInfo::new(MAX_DEPTH, &table)
                .set_max_nodes(cfg.max_nodes, cfg.max_nodes)
                .quiet(true);
            let outcome = match search(&mut board, &mut eval, &mut info) {
                Some(o) => o,
                None => break,
            };
            let mv = match outcome.next() {
                Some(m) => m,
                None => break,
            };
            let data = build_nn_repr5(&board);
            let score = outcome.score().clamp(i16::MIN as i32, i16::MAX as i32) as i16;
            positions.push((data, score));
            board.do_move(mv);
            plies += 1;
        }

        let outcome = if hit_cap {
            GameResult::Draw
        } else {
            board.game_result().unwrap_or(GameResult::Draw)
        };
        for (data, score) in positions.iter() {
            let result = result_for(data.white_to_move, outcome);
            push_entry(&mut body, data, *score, result, cfg.half_komi);
        }
        positions_done.fetch_add(positions.len() as u64, Ordering::Relaxed);

        if body.len() >= TARGET_CHUNK_BYTES {
            if tx.send(make_chunk(&body)).is_err() {
                return;
            }
            body.clear();
        }

        let n = games_done.fetch_add(1, Ordering::Relaxed) + 1;
        if n % 100 == 0 {
            eprintln!("datagen5self: {n} games, {} positions", positions_done.load(Ordering::Relaxed));
        }
    }

    if !body.is_empty() {
        let _ = tx.send(make_chunk(&body));
    }
}

/// Generate a Topaz self-play dataset and write it to `cfg.output`.
pub fn run_selfplay(cfg: SelfPlay5Config) -> io::Result<()> {
    assert!(cfg.threads >= 1, "need at least one thread");
    let start = Instant::now();
    println!(
        "datagen5self: {} games, {} threads, topaz {} nodes/move, {} random plies, komi {} -> {}",
        cfg.num_games, cfg.threads, cfg.max_nodes, cfg.random_plies, cfg.half_komi, cfg.output
    );

    let book = match &cfg.book_path {
        Some(p) => {
            let b = Arc::new(load_book(p)?);
            println!("datagen5self: opening book = {} ({} positions, standard play)", p, b.len());
            Some(b)
        }
        None => None,
    };

    let (tx, rx) = mpsc::channel::<Vec<u8>>();
    let out_path = cfg.output.clone();
    let writer = thread::spawn(move || -> io::Result<u64> {
        let mut file = BufWriter::new(File::create(&out_path)?);
        let mut bytes = 0u64;
        while let Ok(chunk) = rx.recv() {
            file.write_all(&chunk)?;
            bytes += chunk.len() as u64;
        }
        file.flush()?;
        Ok(bytes)
    });

    let games_done = Arc::new(AtomicU64::new(0));
    let positions_done = Arc::new(AtomicU64::new(0));

    let base = cfg.num_games / cfg.threads;
    let extra = cfg.num_games % cfg.threads;
    let mut handles = Vec::new();
    for t in 0..cfg.threads {
        let games = base + if t < extra { 1 } else { 0 };
        if games == 0 {
            continue;
        }
        let tx = tx.clone();
        let cfg = cfg.clone();
        let book = book.clone();
        let games_done = games_done.clone();
        let positions_done = positions_done.clone();
        handles.push(thread::spawn(move || {
            worker_selfplay(games, &cfg, book, tx, &games_done, &positions_done);
            let _ = t;
        }));
    }
    drop(tx);

    for h in handles {
        h.join().expect("worker thread panicked");
    }
    let bytes = writer.join().expect("writer thread panicked")?;

    let secs = start.elapsed().as_secs_f64();
    let positions = positions_done.load(Ordering::Relaxed);
    println!(
        "datagen5self done: {} games, {} positions, {:.1} MB in {:.1}s ({:.0} pos/s) -> {}",
        games_done.load(Ordering::Relaxed),
        positions,
        bytes as f64 / (1024.0 * 1024.0),
        secs,
        positions as f64 / secs.max(1e-9),
        cfg.output,
    );
    Ok(())
}
