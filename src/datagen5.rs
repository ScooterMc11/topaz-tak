//! 5x5 **tiltak-driven** self-play training-data generator → "TAK6" binpack.
//!
//! Unlike [`crate::datagen`] (which self-plays with Topaz's own search on Board6), this module
//! drives the **tiltak** engine as a TEI subprocess to label 5x5 positions for the double-black-stack
//! variant (komi 0). The black-stack rule only fires at ply 1, which tiltak (standard rules) rejects,
//! so **Topaz generates the opening** (forced `2xx` + random flats) and hands tiltak a TPS at
//! `move_num >= 2`; tiltak then plays out standard Tak, giving a move + win-probability per ply.
//!
//! Per position we record `(BoardData5, score)` where `score` is the side-to-move-relative eval such
//! that `sigmoid(score/400) = p` (tiltak's STM win-prob), then backfill the game's WDL result. The
//! on-disk format is byte-identical to [`crate::datagen`] (see that module's header) so the same
//! `topaz checkdata` validator and the bullet trainer (`examples/tak5.rs`) consume it.

